//! Deterministic browser-page documentation and manifest projection.
//!
//! This module consumes the already-admitted [`PageBuildManifest`]. It does not
//! invent a second filesystem grammar or page metadata vocabulary. In
//! particular, `rpc_dependencies` are outbound calls made by a page; they are
//! never operation identity owned by the page.

use crate::{project::sha256_hex, PageBuildManifest};
use serde::{Deserialize, Serialize};
use std::{
    fs::{self, OpenOptions},
    io::Write,
    path::{Path, PathBuf},
    process,
    time::{SystemTime, UNIX_EPOCH},
};
use thiserror::Error;

pub const WEB_PAGE_MANIFEST_SCHEMA: &str = "ores.web.page-manifest/v1";
pub const WEB_PAGE_DOCS_MARKER: &str =
    "<!-- @generated by ores-api-docs page docs; do not edit -->";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct WebPageManifest {
    pub schema: String,
    pub generated_by: String,
    pub route_root: String,
    pub manifest_sha256: String,
    pub pages: Vec<WebPageManifestEntry>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct WebPageManifestEntry {
    pub canonical_url: String,
    pub source_page_rs: String,
    pub source_gen_rs: Option<String>,
    pub source_sha256: String,
    pub axum_paths: Vec<String>,
    pub renderer: String,
    pub delivery: String,
    pub render_mode: String,
    pub revalidate_secs: Option<u64>,
    pub on_demand: Option<String>,
    pub title: Option<String>,
    pub summary: Option<String>,
    pub auth: String,
    pub stability: String,
    pub database: String,
    pub features: Vec<String>,
    pub data_sources: Vec<String>,
    pub tags: Vec<String>,
    pub rpc_dependencies: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WebPageDocsOutputs {
    pub manifest_path: PathBuf,
    pub markdown_path: PathBuf,
    pub html_path: PathBuf,
}

#[derive(Debug, Error)]
pub enum WebPageDocsError {
    #[error("I/O at {path}: {source}")]
    Io {
        path: String,
        #[source]
        source: std::io::Error,
    },
    #[error("JSON: {0}")]
    Json(#[from] serde_json::Error),
    #[error("generated output ownership refused at {path}: {reason}")]
    Ownership { path: String, reason: String },
    #[error("generated output drift at {path}")]
    Drift { path: String },
}

pub fn web_page_manifest(
    repo_root: &Path,
    build: &PageBuildManifest,
) -> Result<WebPageManifest, WebPageDocsError> {
    let mut pages = Vec::with_capacity(build.routes.len());
    for route in &build.routes {
        let source_path = repo_root.join(&route.source);
        let source = fs::read(&source_path).map_err(|source| WebPageDocsError::Io {
            path: source_path.display().to_string(),
            source,
        })?;
        let mut rpc_dependencies = route
            .data_sources
            .iter()
            .filter_map(|value| value.strip_prefix("rpc:"))
            .map(ToOwned::to_owned)
            .collect::<Vec<_>>();
        rpc_dependencies.sort();
        rpc_dependencies.dedup();

        let mut features = route.features.clone();
        features.sort();
        features.dedup();
        let mut data_sources = route.data_sources.clone();
        data_sources.sort();
        data_sources.dedup();
        let mut tags = route.tags.clone();
        tags.sort();
        tags.dedup();
        let mut axum_paths = route.axum_paths.clone();
        axum_paths.sort();
        axum_paths.dedup();

        pages.push(WebPageManifestEntry {
            canonical_url: route.canonical_path.clone(),
            source_page_rs: route.source.clone(),
            source_gen_rs: route.generator.clone(),
            source_sha256: sha256_hex(&source),
            axum_paths,
            renderer: route.renderer.clone(),
            delivery: route.delivery.clone(),
            render_mode: route.render.clone(),
            revalidate_secs: route.revalidate_secs,
            on_demand: route.on_demand.clone(),
            title: route.title.clone(),
            summary: route.summary.clone(),
            auth: route.auth.clone(),
            stability: route.stability.clone(),
            database: route.database.clone(),
            features,
            data_sources,
            tags,
            rpc_dependencies,
        });
    }
    pages.sort_by(|left, right| {
        left.canonical_url
            .cmp(&right.canonical_url)
            .then_with(|| left.source_page_rs.cmp(&right.source_page_rs))
    });

    let semantic = serde_json::to_vec(&pages)?;
    Ok(WebPageManifest {
        schema: WEB_PAGE_MANIFEST_SCHEMA.to_owned(),
        generated_by: env!("CARGO_PKG_VERSION").to_owned(),
        route_root: build.route_root.clone(),
        manifest_sha256: sha256_hex(&semantic),
        pages,
    })
}

#[must_use]
pub fn render_web_page_docs_markdown(manifest: &WebPageManifest) -> String {
    let mut out = String::new();
    out.push_str(WEB_PAGE_DOCS_MARKER);
    out.push_str("\n# Web pages\n\n");
    out.push_str(&format!(
        "Manifest: `{}` · digest: `{}`\n\n",
        manifest.schema, manifest.manifest_sha256
    ));
    out.push_str("| URL | Source | Render | Auth | RPC dependencies |\n");
    out.push_str("| --- | --- | --- | --- | --- |\n");
    for page in &manifest.pages {
        let rpc = if page.rpc_dependencies.is_empty() {
            "—".to_owned()
        } else {
            page.rpc_dependencies.join(", ")
        };
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` / `{}` | `{}` | {} |\n",
            markdown_cell(&page.canonical_url),
            markdown_cell(&page.source_page_rs),
            markdown_cell(&page.renderer),
            markdown_cell(&page.render_mode),
            markdown_cell(&page.auth),
            markdown_cell(&rpc),
        ));
    }
    out
}

#[must_use]
pub fn render_web_page_docs_html(manifest: &WebPageManifest) -> String {
    let mut rows = String::new();
    for page in &manifest.pages {
        let rpc = if page.rpc_dependencies.is_empty() {
            "—".to_owned()
        } else {
            page.rpc_dependencies.join(", ")
        };
        let render = format!("{} / {}", page.renderer, page.render_mode);
        rows.push_str("<tr>");
        for value in [
            page.canonical_url.as_str(),
            page.source_page_rs.as_str(),
            render.as_str(),
            page.auth.as_str(),
            rpc.as_str(),
        ] {
            rows.push_str("<td><code>");
            rows.push_str(&html_escape(value));
            rows.push_str("</code></td>");
        }
        rows.push_str("</tr>\n");
    }
    format!(
        "{marker}\n<!doctype html>\n<meta charset=\"utf-8\">\n<title>Web pages</title>\n<h1>Web pages</h1>\n<p>Manifest <code>{schema}</code> · digest <code>{digest}</code></p>\n<table><thead><tr><th>URL</th><th>Source</th><th>Render</th><th>Auth</th><th>RPC dependencies</th></tr></thead><tbody>\n{rows}</tbody></table>\n",
        marker = WEB_PAGE_DOCS_MARKER,
        schema = html_escape(&manifest.schema),
        digest = html_escape(&manifest.manifest_sha256),
    )
}

pub fn sync_web_page_docs(
    repo_root: &Path,
    build: &PageBuildManifest,
    out_dir: &Path,
    check: bool,
) -> Result<WebPageDocsOutputs, WebPageDocsError> {
    let manifest = web_page_manifest(repo_root, build)?;
    let mut manifest_bytes = serde_json::to_vec_pretty(&manifest)?;
    manifest_bytes.push(b'\n');
    let markdown = render_web_page_docs_markdown(&manifest).into_bytes();
    let html = render_web_page_docs_html(&manifest).into_bytes();

    let manifest_path = out_dir.join("page-manifest.json");
    let markdown_path = out_dir.join("pages.md");
    let html_path = out_dir.join("pages.html");

    sync_owned_file(&manifest_path, &manifest_bytes, check, OutputKind::Manifest)?;
    sync_owned_file(&markdown_path, &markdown, check, OutputKind::MarkedText)?;
    sync_owned_file(&html_path, &html, check, OutputKind::MarkedText)?;

    Ok(WebPageDocsOutputs {
        manifest_path,
        markdown_path,
        html_path,
    })
}

#[derive(Clone, Copy)]
enum OutputKind {
    Manifest,
    MarkedText,
}

fn sync_owned_file(
    path: &Path,
    expected: &[u8],
    check: bool,
    kind: OutputKind,
) -> Result<(), WebPageDocsError> {
    if check {
        let actual = fs::read(path).map_err(|source| WebPageDocsError::Io {
            path: path.display().to_string(),
            source,
        })?;
        if actual != expected {
            return Err(WebPageDocsError::Drift {
                path: path.display().to_string(),
            });
        }
        return Ok(());
    }

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|source| WebPageDocsError::Io {
            path: parent.display().to_string(),
            source,
        })?;
    }
    verify_owned_destination(path, kind)?;

    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let file_name = path
        .file_name()
        .and_then(|value| value.to_str())
        .unwrap_or("page-docs");
    let temp = path.with_file_name(format!(".{file_name}.ores-tmp-{}-{nonce:x}", process::id()));
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)
        .map_err(|source| WebPageDocsError::Io {
            path: temp.display().to_string(),
            source,
        })?;
    if let Err(source) = file.write_all(expected).and_then(|_| file.sync_all()) {
        let _ = fs::remove_file(&temp);
        return Err(WebPageDocsError::Io {
            path: temp.display().to_string(),
            source,
        });
    }
    drop(file);

    // Re-check immediately before replacement so a changed destination cannot
    // turn a reviewed generated path into an authored/symlink overwrite.
    if let Err(error) = verify_owned_destination(path, kind) {
        let _ = fs::remove_file(&temp);
        return Err(error);
    }
    if let Err(source) = fs::rename(&temp, path) {
        let _ = fs::remove_file(&temp);
        return Err(WebPageDocsError::Io {
            path: path.display().to_string(),
            source,
        });
    }
    Ok(())
}

fn verify_owned_destination(path: &Path, kind: OutputKind) -> Result<(), WebPageDocsError> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(source) => {
            return Err(WebPageDocsError::Io {
                path: path.display().to_string(),
                source,
            })
        }
    };
    if metadata.file_type().is_symlink() || !metadata.file_type().is_file() {
        return Err(WebPageDocsError::Ownership {
            path: path.display().to_string(),
            reason: "destination must be a regular generated file".to_owned(),
        });
    }
    let bytes = fs::read(path).map_err(|source| WebPageDocsError::Io {
        path: path.display().to_string(),
        source,
    })?;
    let owned = match kind {
        OutputKind::MarkedText => bytes.starts_with(WEB_PAGE_DOCS_MARKER.as_bytes()),
        OutputKind::Manifest => {
            serde_json::from_slice::<serde_json::Value>(&bytes)
                .ok()
                .and_then(|value| {
                    value
                        .get("schema")
                        .and_then(|value| value.as_str())
                        .map(str::to_owned)
                })
                .as_deref()
                == Some(WEB_PAGE_MANIFEST_SCHEMA)
        }
    };
    if !owned {
        return Err(WebPageDocsError::Ownership {
            path: path.display().to_string(),
            reason: "existing file is not owned by the web page docs generator".to_owned(),
        });
    }
    Ok(())
}

fn markdown_cell(value: &str) -> String {
    value.replace('|', "\\|").replace('\n', " ")
}

fn html_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::PageBuildRoute;

    fn temp_root(label: &str) -> PathBuf {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("clock after epoch")
            .as_nanos();
        let root = std::env::temp_dir().join(format!(
            "ores-api-docs-page-docs-{label}-{}-{unique}",
            process::id()
        ));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).expect("fixture root");
        root
    }

    fn fixture(root: &Path) -> PageBuildManifest {
        let page_dir = root.join("src/pages/users/[id]");
        fs::create_dir_all(&page_dir).unwrap();
        fs::write(page_dir.join("page.rs"), "pub async fn page() {}\n").unwrap();
        fs::write(
            page_dir.join("gen.rs"),
            "pub async fn generate_static_params() {}\n",
        )
        .unwrap();
        PageBuildManifest {
            schema_version: "1.2.0".to_owned(),
            route_root: "src/pages".to_owned(),
            wasm_have_header: "x-ores-wasm-have".to_owned(),
            wasm_have_cookie: "ores_wasm_have".to_owned(),
            routes: vec![PageBuildRoute {
                source: "src/pages/users/[id]/page.rs".to_owned(),
                generator: Some("src/pages/users/[id]/gen.rs".to_owned()),
                canonical_path: "/users/{id}".to_owned(),
                axum_paths: vec!["/users/{id}".to_owned()],
                dioxus_paths: vec!["/users/:id".to_owned()],
                renderer: "leptos".to_owned(),
                delivery: "ssr_only".to_owned(),
                render: "static_with_fallback".to_owned(),
                revalidate_secs: Some(60),
                on_demand: None,
                title: Some("User".to_owned()),
                summary: None,
                auth: "session".to_owned(),
                stability: "stable".to_owned(),
                database: "read_only".to_owned(),
                features: vec!["users".to_owned(), "users".to_owned()],
                data_sources: vec![
                    "rpc:demo.users.find".to_owned(),
                    "orm:user_read".to_owned(),
                    "rpc:demo.users.find".to_owned(),
                ],
                tags: vec!["account".to_owned()],
                css: None,
                wasm: None,
            }],
        }
    }

    #[test]
    fn outbound_rpc_calls_are_dependencies_not_page_operations() {
        let root = temp_root("rpc-deps");
        let manifest = web_page_manifest(&root, &fixture(&root)).unwrap();
        assert_eq!(
            manifest.pages[0].rpc_dependencies,
            vec!["demo.users.find".to_owned()]
        );
        let json = serde_json::to_string(&manifest).unwrap();
        assert!(json.contains("rpcDependencies"));
        assert!(!json.contains("rpcOperations"));
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn projection_is_deterministic_and_check_mode_is_read_only() {
        let root = temp_root("deterministic");
        let build = fixture(&root);
        let out = root.join("generated/web");
        sync_web_page_docs(&root, &build, &out, false).unwrap();
        let first = fs::read(out.join("page-manifest.json")).unwrap();
        sync_web_page_docs(&root, &build, &out, true).unwrap();
        let second = fs::read(out.join("page-manifest.json")).unwrap();
        assert_eq!(first, second);
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn refuses_authored_output_and_symlink_destination() {
        let root = temp_root("ownership");
        let build = fixture(&root);
        let out = root.join("generated/web");
        fs::create_dir_all(&out).unwrap();
        fs::write(out.join("pages.md"), "authored\n").unwrap();
        let error = sync_web_page_docs(&root, &build, &out, false).unwrap_err();
        assert!(matches!(error, WebPageDocsError::Ownership { .. }));

        #[cfg(unix)]
        {
            use std::os::unix::fs::symlink;
            fs::remove_file(out.join("pages.md")).unwrap();
            fs::write(out.join("target"), WEB_PAGE_DOCS_MARKER).unwrap();
            symlink(out.join("target"), out.join("pages.md")).unwrap();
            let error = sync_web_page_docs(&root, &build, &out, false).unwrap_err();
            assert!(matches!(error, WebPageDocsError::Ownership { .. }));
        }

        fs::remove_dir_all(root).unwrap();
    }
}
