//! Generated Rust type-state builder surface.
//!
//! The skeleton (state markers, plan storage, terminals) is hand-written in
//! `rust/src/rpc_fluent.rs`. Everything the catalog owns — the option methods,
//! their bounds, their enums and the state transitions — is generated here, so
//! the Rust surface cannot drift from the TypeScript one.
//!
//! Exclusive groups become type parameters. `use_json` is implemented only for
//! `Serial = Unset` and returns `Serial = Set`, so a second selection has no
//! method to call and fails to compile.

use super::model::{AppliesTo, Catalog, Option_};
use super::names::Language;
use std::fmt::Write as _;

const NOTICE: &str =
    "// Generated by `cargo run --bin ores-rpc-docs -- generate`. Do not edit by hand.";

/// Type parameter name for an exclusive group, e.g. `serialization` -> `Serial`.
fn type_param(group_id: &str) -> String {
    match group_id {
        "serialization" => "Serial".to_owned(),
        "auth_mode" => "Auth".to_owned(),
        "ip_version" => "Ip".to_owned(),
        "rate_limit" => "Rate".to_owned(),
        "stream_rate_limit" => "StreamRate".to_owned(),
        other => Language::Go.method_name(other),
    }
}

/// Groups that appear on a surface, in catalog order.
fn surface_groups(catalog: &Catalog, surface: AppliesTo) -> Vec<String> {
    catalog
        .exclusive_groups
        .iter()
        .filter(|group| {
            catalog.options.iter().any(|option| {
                option.exclusive_group.as_deref() == Some(group.exclusive_group_id.as_str())
                    && on_surface(option, surface)
            })
        })
        .map(|group| group.exclusive_group_id.clone())
        .collect()
}

fn on_surface(option: &Option_, surface: AppliesTo) -> bool {
    match surface {
        AppliesTo::Stream => option.applies_to.on_stream(),
        _ => option.applies_to.on_unary(),
    }
}

pub fn render(catalog: &Catalog) -> String {
    let mut out = String::with_capacity(48 * 1024);
    let _ = writeln!(out, "{NOTICE}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "use super::rpc_fluent::{{Set, StreamCall, UnaryCall, Unset}};"
    );
    let _ = writeln!(out, "use serde_json::{{json, Value}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// Catalog version this surface was generated from.");
    let _ = writeln!(
        out,
        "pub const CATALOG_VERSION: &str = {:?};",
        catalog.catalog_version
    );
    let _ = writeln!(
        out,
        "pub const DEFAULT_RPC_PATH: &str = {:?};",
        catalog.rpc_path
    );
    let _ = writeln!(out);

    render_redaction(&mut out, catalog);
    render_enums(&mut out, catalog);
    render_surface(&mut out, catalog, AppliesTo::Unary);
    render_surface(&mut out, catalog, AppliesTo::Stream);
    out
}

fn render_enums(out: &mut String, catalog: &Catalog) {
    for catalog_enum in &catalog.enums {
        let name = Language::Go.method_name(&catalog_enum.enum_id);
        let _ = writeln!(
            out,
            "/// `{}` in the catalog; wire values are stable.",
            catalog_enum.namespace
        );
        let _ = writeln!(
            out,
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]"
        );
        let _ = writeln!(out, "pub enum {name} {{");
        for variant in &catalog_enum.variants {
            let _ = writeln!(
                out,
                "    {},",
                Language::Rust.variant_name(&variant.variant_id)
            );
        }
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
        let _ = writeln!(out, "impl {name} {{");
        let _ = writeln!(
            out,
            "    /// Canonical wire value written into the request plan."
        );
        let _ = writeln!(out, "    #[must_use]");
        let _ = writeln!(out, "    pub fn wire_value(self) -> Value {{");
        let _ = writeln!(out, "        match self {{");
        for variant in &catalog_enum.variants {
            let _ = writeln!(
                out,
                "            Self::{} => json!({}),",
                Language::Rust.variant_name(&variant.variant_id),
                serde_json::to_string(&variant.wire_value).unwrap_or_else(|_| "null".to_owned())
            );
        }
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "    /// Header effect this variant applies to the outbound request."
        );
        let _ = writeln!(out, "    #[must_use]");
        let _ = writeln!(
            out,
            "    pub fn header_effect(self) -> &'static [(&'static str, &'static str)] {{"
        );
        let _ = writeln!(out, "        match self {{");
        for variant in &catalog_enum.variants {
            let mut effects: Vec<String> = Vec::new();
            if let Some(content_type) = &variant.content_type {
                effects.push(format!("(\"content-type\", {content_type:?})"));
                effects.push(format!("(\"accept\", {content_type:?})"));
            }
            if let Some(content_encoding) = &variant.content_encoding {
                effects.push(format!("(\"content-encoding\", {content_encoding:?})"));
            }
            let _ = writeln!(
                out,
                "            Self::{} => &[{}],",
                Language::Rust.variant_name(&variant.variant_id),
                effects.join(", ")
            );
        }
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
    }
}

fn render_surface(out: &mut String, catalog: &Catalog, surface: AppliesTo) {
    let builder = match surface {
        AppliesTo::Stream => "StreamCall",
        _ => "UnaryCall",
    };
    let groups = surface_groups(catalog, surface);
    let params: Vec<String> = groups.iter().map(|g| type_param(g)).collect();
    let all_params = params.join(", ");

    // Options outside every exclusive group: available in any state.
    let _ = writeln!(
        out,
        "/// Options available on a {} chain in any type-state.",
        if surface == AppliesTo::Stream {
            "streaming"
        } else {
            "unary"
        }
    );
    let _ = writeln!(out, "impl<{all_params}> {builder}<{all_params}> {{");
    for option in catalog.options.iter().filter(|o| on_surface(o, surface)) {
        if option.exclusive_group.is_some() || option.terminal {
            continue;
        }
        render_method(out, option, builder, &params, None);
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    // One impl block per exclusive group, gated on that group being Unset.
    for group_id in &groups {
        let members: Vec<&Option_> = catalog
            .options
            .iter()
            .filter(|o| {
                o.exclusive_group.as_deref() == Some(group_id.as_str()) && on_surface(o, surface)
            })
            .collect();
        if members.is_empty() {
            continue;
        }
        let this_param = type_param(group_id);
        let others: Vec<String> = params
            .iter()
            .filter(|p| *p != &this_param)
            .cloned()
            .collect();
        let generics = if others.is_empty() {
            String::new()
        } else {
            format!("<{}>", others.join(", "))
        };
        // Self type has Unset in this position; the return type has Set.
        let self_args: Vec<String> = params
            .iter()
            .map(|p| {
                if p == &this_param {
                    "Unset".to_owned()
                } else {
                    p.clone()
                }
            })
            .collect();

        let _ = writeln!(
            out,
            "/// `{group_id}` is unspent here. Every method below spends it, so a\n/// contradictory second selection has no method to call."
        );
        let _ = writeln!(out, "impl{generics} {builder}<{}> {{", self_args.join(", "));
        for option in members {
            render_method(out, option, builder, &params, Some(&this_param));
        }
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
    }
}

fn render_method(
    out: &mut String,
    option: &Option_,
    builder: &str,
    params: &[String],
    spends: Option<&str>,
) {
    let name = Language::Rust.method_name(&option.option_id);
    let args = rust_params(option);
    let return_args: Vec<String> = params
        .iter()
        .map(|p| {
            if Some(p.as_str()) == spends {
                "Set".to_owned()
            } else {
                p.clone()
            }
        })
        .collect();
    let return_type = if return_args.is_empty() {
        builder.to_owned()
    } else {
        format!("{builder}<{}>", return_args.join(", "))
    };

    let _ = writeln!(out, "    /// {}", option.summary);
    if let Some(capability) = &option.requires_capability {
        let _ = writeln!(
            out,
            "    ///\n    /// # Errors\n    /// Refused unless the client declares the `{capability}` capability."
        );
    }
    if option.secret {
        let _ = writeln!(
            out,
            "    ///\n    /// The credential reaches the wire but is redacted from every plan."
        );
    }
    let _ = writeln!(out, "    #[must_use]");
    let _ = writeln!(
        out,
        "    pub fn {name}(mut self{}) -> {return_type} {{",
        if args.is_empty() {
            String::new()
        } else {
            format!(", {args}")
        }
    );
    render_body(out, option);
    let _ = writeln!(out, "        self.transmute()");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
}

fn render_body(out: &mut String, option: &Option_) {
    // Bounds are enforced where the value enters, mirroring the TypeScript client.
    for param in &option.params {
        let name = &param.name;
        // An unsigned zero lower bound is already enforced by the type.
        let unsigned = matches!(param.ty.as_str(), "u8" | "u32");
        if let Some(minimum) = param.minimum.filter(|m| !(unsigned && *m == 0.0)) {
            let _ = writeln!(
                out,
                "        assert!({name} >= {}, \"{}: {name} must be at least {}\");",
                render_bound(param, minimum),
                option.option_id,
                render_bound(param, minimum)
            );
        }
        if let Some(maximum) = param.maximum {
            let _ = writeln!(
                out,
                "        assert!({name} <= {}, \"{}: {name} must be at most {}\");",
                render_bound(param, maximum),
                option.option_id,
                render_bound(param, maximum)
            );
        }
        if let Some(max_length) = param.max_length {
            let _ = writeln!(
                out,
                "        assert!({name}.len() <= {max_length}, \"{}: {name} must be at most {max_length} characters\");",
                option.option_id
            );
        }
    }

    match option.option_id.as_str() {
        "add_header" => {
            let _ = writeln!(
                out,
                "        self.set_header(&name.to_ascii_lowercase(), value);"
            );
            return;
        }
        "add_headers" => {
            let _ = writeln!(
                out,
                "        for (name, value) in values {{\n            self.set_header(&name.to_ascii_lowercase(), value);\n        }}"
            );
            return;
        }
        "add_path_field" => {
            let _ = writeln!(out, "        self.set_section(\"path\", name, value);");
            return;
        }
        "add_query_field" => {
            let _ = writeln!(out, "        self.set_section(\"query\", name, value);");
            return;
        }
        "add_body_field" => {
            let _ = writeln!(out, "        self.set_body_field(name, value);");
            return;
        }
        "with_body" => {
            let _ = writeln!(out, "        self.set_body(body);");
            return;
        }
        _ => {}
    }

    let Some(field) = option.plan_field.as_deref() else {
        return;
    };

    if option.params.iter().any(|p| p.ty == "callback") {
        // The plan records only a count — a closure is not data — but the
        // builder retains the callback so a transport can actually invoke it.
        let kind = if is_progress_hook(option) {
            "progress"
        } else {
            "retry"
        };
        let _ = writeln!(
            out,
            "        self.push_{kind}_hook({field:?}, ::std::sync::Arc::new(callback));"
        );
        return;
    }
    if let Some(constant) = &option.plan_value {
        let _ = writeln!(
            out,
            "        self.set_plan({field:?}, json!({}));",
            serde_json::to_string(constant).unwrap_or_else(|_| "null".to_owned())
        );
    } else if option.params.len() > 1 {
        let entries: Vec<String> = option
            .params
            .iter()
            .map(|p| format!("{:?}: {}", p.name, p.name))
            .collect();
        let _ = writeln!(
            out,
            "        self.set_plan({field:?}, json!({{ {} }}));",
            entries.join(", ")
        );
    } else if let Some(param) = option.params.first() {
        let value = match param.ty.as_str() {
            "enum" => format!("{}.wire_value()", param.name),
            "secret_string" | "string" | "url" => format!("json!({})", param.name),
            _ => format!("json!({})", param.name),
        };
        let _ = writeln!(out, "        self.set_plan({field:?}, {value});");
        if param.ty == "secret_string" {}
    }

    // Wire header effects.
    if let Some(wire) = &option.wire {
        for name in &wire.drop_headers {
            let _ = writeln!(out, "        self.drop_header({name:?});");
        }
        for (name, template) in &wire.headers {
            let rendered = render_header_template(template, option);
            let _ = writeln!(out, "        self.set_wire_header({name:?}, {rendered});");
            if option.secret {
                let _ = writeln!(out, "        self.mark_secret_header({name:?});");
            }
        }
        if wire.headers_from_enum.is_some() {
            if let Some(param) = option.params.iter().find(|p| p.ty == "enum") {
                let _ = writeln!(
                    out,
                    "        for (name, value) in {}.header_effect() {{\n            self.set_wire_header(name, (*value).to_owned());\n        }}",
                    param.name
                );
            }
        }
    }
}

fn render_header_template(template: &str, option: &Option_) -> String {
    // `{name}` interpolates a parameter; `{flag:a|b}` selects on a boolean.
    if let Some(start) = template.find('{') {
        let end = template[start..].find('}').map(|offset| start + offset);
        if let Some(end) = end {
            let expression = &template[start + 1..end];
            let prefix = &template[..start];
            let suffix = &template[end + 1..];
            if let Some((name, choices)) = expression.split_once(':') {
                let (when_true, when_false) = choices.split_once('|').unwrap_or((choices, ""));
                return format!(
                    "format!(\"{{}}{{}}{{}}\", {prefix:?}, if {name} {{ {when_true:?} }} else {{ {when_false:?} }}, {suffix:?})"
                );
            }
            let is_numeric = option
                .params
                .iter()
                .any(|p| p.name == expression && matches!(p.ty.as_str(), "u8" | "u32" | "i64"));
            let accessor = if is_numeric {
                expression.to_owned()
            } else if option
                .params
                .iter()
                .any(|p| p.name == expression && p.ty == "enum")
            {
                format!("{expression}.wire_value()")
            } else {
                expression.to_owned()
            };
            return format!("format!(\"{{}}{{}}{{}}\", {prefix:?}, {accessor}, {suffix:?})");
        }
    }
    format!("{template:?}.to_owned()")
}

fn render_bound(param: &super::model::Param, value: f64) -> String {
    match param.ty.as_str() {
        "f64" => format!("{value:?}"),
        _ => format!("{}", value as i64),
    }
}

fn rust_params(option: &Option_) -> String {
    option
        .params
        .iter()
        .map(|param| {
            let ty = match param.ty.as_str() {
                "enum" => param
                    .enum_id
                    .as_deref()
                    .map(|id| Language::Go.method_name(id))
                    .unwrap_or_else(|| "()".to_owned()),
                "bool" => "bool".to_owned(),
                "u8" => "u8".to_owned(),
                "u32" => "u32".to_owned(),
                "i64" => "i64".to_owned(),
                "f64" => "f64".to_owned(),
                "string" | "secret_string" | "url" => "&str".to_owned(),
                "json_object" => "serde_json::Map<String, Value>".to_owned(),
                "json" => "Value".to_owned(),
                "callback" => callback_signature(param).to_owned(),
                _ => "Value".to_owned(),
            };
            format!("{}: {ty}", param.name)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Progress hooks take byte counts; retry hooks take an attempt and a cause.
fn is_progress_hook(option: &Option_) -> bool {
    option.params.iter().any(|param| {
        param
            .signature
            .as_deref()
            .is_some_and(|signature| signature.contains("_bytes"))
    })
}

/// Rust type for a callback parameter, chosen from its declared signature.
fn callback_signature(param: &super::model::Param) -> &'static str {
    match param.signature.as_deref() {
        Some(signature) if signature.contains("_bytes") => {
            "impl Fn(u64, Option<u64>) + Send + Sync + 'static"
        }
        _ => "impl Fn(u8, &str) + Send + Sync + 'static",
    }
}

/// Emit the final-boundary redaction tables.
///
/// These are data, not policy decisions made here: the catalog owns which
/// header names and URL fields carry credentials, so Rust and TypeScript
/// cannot drift apart on what a plan hides.
fn render_redaction(out: &mut String, catalog: &Catalog) {
    let redaction = &catalog.plan_redaction;
    let _ = writeln!(
        out,
        "/// Placeholder substituted for any redacted value in a request plan."
    );
    let _ = writeln!(
        out,
        "pub const REDACTED: &str = {:?};",
        redaction.redacted_placeholder
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "/// Header names redacted outright, lowercase, sorted."
    );
    let _ = writeln!(
        out,
        "pub const REDACTED_HEADER_NAMES: &[&str] = &[{}];",
        redaction
            .header_names
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "/// Substrings that mark a header name as credential-bearing."
    );
    let _ = writeln!(
        out,
        "pub const REDACTED_HEADER_PATTERNS: &[&str] = &[{}];",
        redaction
            .header_name_patterns
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "/// Plan fields holding a URL whose userinfo is stripped."
    );
    let _ = writeln!(
        out,
        "pub const REDACTED_URL_FIELDS: &[&str] = &[{}];",
        redaction
            .url_fields
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(out);
}
