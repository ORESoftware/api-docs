//! Canonical filesystem layout for generated RPC operation modules.
//!
//! The low-level transport/runtime client is intentionally outside each language's
//! `generated/` directory. Only operation-specific generated modules live under
//! `src/langs/<language>/generated/`, namespaced by the canonical dotted RPC key
//! after dropping the service/root segment.

use std::path::PathBuf;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RpcSdkLanguage {
    Rust,
    Go,
    Dart,
    TypeScript,
    Gleam,
}

impl RpcSdkLanguage {
    pub const ALL: [Self; 5] = [
        Self::Rust,
        Self::Go,
        Self::Dart,
        Self::TypeScript,
        Self::Gleam,
    ];

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Rust => "rust",
            Self::Go => "go",
            Self::Dart => "dart",
            Self::TypeScript => "typescript",
            Self::Gleam => "gleam",
        }
    }

    /// Repository directory name. Go deliberately uses `golang` so the
    /// generated tree is unambiguous to humans while the manifest language id
    /// remains the canonical `go`.
    pub const fn directory_name(self) -> &'static str {
        match self {
            Self::Rust => "rust",
            Self::Go => "golang",
            Self::Dart => "dart",
            Self::TypeScript => "typescript",
            Self::Gleam => "gleam",
        }
    }

    pub const fn extension(self) -> &'static str {
        match self {
            Self::Rust => "rs",
            Self::Go => "go",
            Self::Dart => "dart",
            Self::TypeScript => "ts",
            Self::Gleam => "gleam",
        }
    }

    /// Root containing operation-specific generated modules for this language.
    /// There are exactly five such roots, one per supported language.
    pub fn generated_root(self) -> PathBuf {
        PathBuf::from("src")
            .join("langs")
            .join(self.directory_name())
            .join("generated")
    }

    /// Runtime/transport code is intentionally outside `generated/` but remains
    /// in the same language tree.
    pub fn runtime_root(self) -> PathBuf {
        PathBuf::from("src")
            .join("langs")
            .join(self.directory_name())
            .join("runtime")
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RpcOperationModulePath {
    pub service_root: String,
    pub namespace: Vec<String>,
    pub operation: String,
}

impl RpcOperationModulePath {
    pub fn from_rpc_key(rpc_key: &str) -> Result<Self, String> {
        let segments = rpc_key.split('.').collect::<Vec<_>>();
        if segments.len() < 2 {
            return Err(format!(
                "RPC operation key {rpc_key:?} must contain a service/root segment and operation"
            ));
        }
        for segment in &segments {
            if !is_snake_identifier(segment) {
                return Err(format!(
                    "RPC operation key {rpc_key:?} contains non-snake_case segment {segment:?}"
                ));
            }
        }
        let service_root = segments[0].to_owned();
        let operation = segments[segments.len() - 1].to_owned();
        let namespace = segments[1..segments.len() - 1]
            .iter()
            .map(|value| (*value).to_owned())
            .collect();
        Ok(Self {
            service_root,
            namespace,
            operation,
        })
    }

    pub fn relative_operation_path(&self, language: RpcSdkLanguage) -> PathBuf {
        let mut path = language.generated_root();
        for segment in &self.namespace {
            path.push(segment);
        }
        let stem = match language {
            // Gleam module names are their filesystem names, so preserve a
            // valid snake_case module identifier instead of projecting kebab-case.
            RpcSdkLanguage::Gleam => self.operation.clone(),
            _ => self.operation.replace('_', "-"),
        };
        path.push(format!("{stem}.{}", language.extension()));
        path
    }
}

pub const GENERATED_README: &str = r#"# Generated RPC operations

This directory is generated by `ores-stack sync` / `ores-api-docs`.

- Do not edit files in this directory by hand.
- Operation modules are namespaced from the canonical dotted RPC key after the service/root segment.
- Generic RPC transport/runtime code lives outside this directory under the sibling `runtime` directory.
- Regeneration temporarily makes this tree writable and then restores read-only permissions.
- Git does not preserve ordinary read-only permission bits, so the generator reapplies read-only permissions after every materialization/check cycle.
"#;

