pub fn generated_source_header(language: RpcSdkLanguage, rpc_key: &str) -> String {
    match language {
        RpcSdkLanguage::TypeScript => format!(
            "/** @generated by ores-api-docs/ores-stack from {rpc_key}; DO NOT EDIT. */\n"
        ),
        RpcSdkLanguage::Dart => format!(
            "// @generated by ores-api-docs/ores-stack from {rpc_key}; DO NOT EDIT.\n"
        ),
        RpcSdkLanguage::Rust => format!(
            "// @generated by ores-api-docs/ores-stack from {rpc_key}; DO NOT EDIT.\n"
        ),
        RpcSdkLanguage::Go => format!(
            "// Code generated by ores-api-docs/ores-stack from {rpc_key}; DO NOT EDIT.\n"
        ),
        RpcSdkLanguage::Gleam => format!(
            "// @generated by ores-api-docs/ores-stack from {rpc_key}; DO NOT EDIT.\n"
        ),
    }
}

fn is_snake_identifier(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_lowercase() || first == '_') {
        return false;
    }
    chars.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sonus_admin_key_maps_to_admin_version_operation_module() {
        let path = RpcOperationModulePath::from_rpc_key(
            "sonus_auris.admin.version.get_version",
        )
        .expect("valid key");
        assert_eq!(path.service_root, "sonus_auris");
        assert_eq!(path.namespace, vec!["admin", "version"]);
        assert_eq!(path.operation, "get_version");
        assert_eq!(
            path.relative_operation_path(RpcSdkLanguage::TypeScript),
            PathBuf::from("src/langs/typescript/generated/admin/version/get-version.ts")
        );
        assert_eq!(
            path.relative_operation_path(RpcSdkLanguage::Rust),
            PathBuf::from("src/langs/rust/generated/admin/version/get-version.rs")
        );
        assert_eq!(
            path.relative_operation_path(RpcSdkLanguage::Go),
            PathBuf::from("src/langs/golang/generated/admin/version/get-version.go")
        );
        assert_eq!(
            path.relative_operation_path(RpcSdkLanguage::Gleam),
            PathBuf::from("src/langs/gleam/generated/admin/version/get_version.gleam")
        );
    }

    #[test]
    fn regular_service_root_is_not_repeated_in_filesystem_namespace() {
        let sonus = RpcOperationModulePath::from_rpc_key("sonus_auris.version.get_version")
            .expect("valid key");
        let canonical = RpcOperationModulePath::from_rpc_key("canonical_cloud.version.get_version")
            .expect("valid key");
        assert_eq!(
            sonus.relative_operation_path(RpcSdkLanguage::Go),
            PathBuf::from("src/langs/golang/generated/version/get-version.go")
        );
        assert_eq!(
            canonical.relative_operation_path(RpcSdkLanguage::Dart),
            PathBuf::from("src/langs/dart/generated/version/get-version.dart")
        );
    }

    #[test]
    fn there_are_exactly_five_generated_roots() {
        let roots = RpcSdkLanguage::ALL
            .into_iter()
            .map(RpcSdkLanguage::generated_root)
            .collect::<std::collections::BTreeSet<_>>();
        assert_eq!(roots.len(), 5);
        assert!(roots.contains(&PathBuf::from("src/langs/rust/generated")));
        assert!(roots.contains(&PathBuf::from("src/langs/golang/generated")));
        assert!(roots.contains(&PathBuf::from("src/langs/dart/generated")));
        assert!(roots.contains(&PathBuf::from("src/langs/typescript/generated")));
        assert!(roots.contains(&PathBuf::from("src/langs/gleam/generated")));
    }

    #[test]
    fn invalid_or_flat_keys_fail_closed() {
        assert!(RpcOperationModulePath::from_rpc_key("get_version").is_err());
        assert!(RpcOperationModulePath::from_rpc_key("Sonus.admin.get_version").is_err());
        assert!(RpcOperationModulePath::from_rpc_key("sonus-auris.admin.get_version").is_err());
    }
}
