fn wasm_client(map: &RouteMap, audience: &str, digest: &str) -> String {
    let allowed = map
        .map
        .keys()
        .map(|key| format!("        {key:?} => true,"))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        r#"// @generated by {generator}; do not edit.
#![forbid(unsafe_code)]

use js_sys::{{Date, Math}};
use serde_json::Value;
use wasm_bindgen::{{prelude::*, JsCast}};
use wasm_bindgen_futures::JsFuture;
use web_sys::{{Request, RequestInit, RequestMode, Response}};

pub const RPC_CONTRACT_SHA256: &str = {digest:?};
pub const RPC_CLIENT_AUDIENCE: &str = {audience:?};
pub const RPC_SERVICE: &str = {service:?};
pub const RPC_HTTP_PATH: &str = {rpc_path:?};

fn allowed_operation(key: &str) -> bool {{
    match key {{
{allowed}
        _ => false,
    }}
}}

#[wasm_bindgen]
pub struct RpcClient {{
    base_url: String,
}}

#[wasm_bindgen]
impl RpcClient {{
    #[wasm_bindgen(constructor)]
    pub fn new(base_url: String) -> Self {{
        Self {{ base_url }}
    }}

    #[wasm_bindgen]
    pub async fn call(&self, key: String, body: JsValue) -> Result<JsValue, JsValue> {{
        if !allowed_operation(&key) {{
            return Err(JsValue::from_str("RPC operation is not generated for this audience"));
        }}
        let id = format!("wasm-{{}}-{{}}", Date::now(), Math::random());
        let body_value: Value = if body.is_undefined() || body.is_null() {{
            Value::Null
        }} else {{
            serde_wasm_bindgen::from_value(body)
                .map_err(|error| JsValue::from_str(&error.to_string()))?
        }};
        let envelope = serde_json::json!({{
            "v": 1,
            "op": "call",
            "id": id,
            "key": key,
            "transport": "http",
            "body": body_value,
        }});
        let serialized = serde_json::to_string(&envelope)
            .map_err(|error| JsValue::from_str(&error.to_string()))?;
        let options = RequestInit::new();
        options.set_method("POST");
        options.set_mode(RequestMode::Cors);
        options.set_body(&JsValue::from_str(&serialized));
        let url = format!("{{}}{{}}", self.base_url.trim_end_matches('/'), RPC_HTTP_PATH);
        let request = Request::new_with_str_and_init(&url, &options)?;
        request.headers().set("content-type", "application/json")?;
        let window = web_sys::window().ok_or_else(|| JsValue::from_str("window is unavailable"))?;
        let response = JsFuture::from(window.fetch_with_request(&request)).await?;
        let response: Response = response.dyn_into()?;
        let json = JsFuture::from(response.json()?).await?;
        let receipt: Value = serde_wasm_bindgen::from_value(json)
            .map_err(|error| JsValue::from_str(&error.to_string()))?;
        if receipt.get("id").and_then(Value::as_str) != envelope.get("id").and_then(Value::as_str)
            || receipt.get("key").and_then(Value::as_str) != envelope.get("key").and_then(Value::as_str)
        {{
            return Err(JsValue::from_str("RPC receipt correlation mismatch"));
        }}
        if receipt.get("ok").and_then(Value::as_bool) != Some(true) {{
            return serde_wasm_bindgen::to_value(&receipt)
                .map(Err)
                .unwrap_or_else(|error| Err(JsValue::from_str(&error.to_string())));
        }}
        serde_wasm_bindgen::to_value(receipt.get("body").unwrap_or(&Value::Null))
            .map_err(|error| JsValue::from_str(&error.to_string()))
    }}
}}
"#,
        generator = GENERATOR,
        digest = digest,
        audience = audience,
        service = map.service,
        rpc_path = RPC_HTTP_PATH,
        allowed = allowed,
    )
}

fn operation_metadata(map: &RouteMap) -> BTreeMap<&str, Value> {
    map.map
        .iter()
        .map(|(key, entry)| {
            (
                key.as_str(),
                serde_json::json!({
                    "rpcKey": entry.rpc_key,
                    "path": entry.path,
                    "methods": entry.methods,
                    "transports": entry.transports,
                }),
            )
        })
        .collect()
}

fn sanitize_package(service: &str) -> String {
    let mut out = service
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '-' {
                character.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect::<String>();
    while out.contains("--") {
        out = out.replace("--", "-");
    }
    out.trim_matches('-').to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_map() -> RouteMap {
        RouteMap::from_json_str(
            r#"{
              "schema_version":"1.0.0",
              "service":"demo-api",
              "map":{
                "ping":{
                  "path":"/v1/ping",
                  "methods":["GET"],
                  "authorization":{"mode":"public"},
                  "transports":["http"]
                }
              }
            }"#,
        )
        .unwrap_or_else(|error| panic!("sample route map failed: {error}"))
    }

    #[test]
    fn emits_one_digest_bound_four_language_bundle() {
        let bundle = rpc_client_bundle(&sample_map(), "crate::dto", "public")
            .unwrap_or_else(|error| panic!("bundle generation failed: {error}"));
        assert_eq!(bundle.manifest.operations, vec!["ping"]);
        assert_eq!(bundle.manifest.http_endpoint, "/v1/rpc");
        assert!(bundle.rust.contains("RPC_CONTRACT_SHA256"));
        assert!(bundle.rust.contains("RPC_HTTP_PATH"));
        assert!(bundle.typescript.contains("new URL(RPC_HTTP_PATH"));
        assert!(bundle.dart.contains("baseUri.resolve(rpcHttpPath)"));
        assert!(bundle.wasm_rust.contains("RPC_HTTP_PATH"));
    }

    #[test]
    fn typescript_make_call_is_the_only_fetch_boundary() {
        let bundle = rpc_client_bundle(&sample_map(), "crate::dto", "public")
            .unwrap_or_else(|error| panic!("bundle generation failed: {error}"));
        let source = &bundle.typescript;

        assert!(source.contains("makeCall(): Promise<RpcOutcome<T, E>>"));
        assert!(!source.contains("executeCall("));
        assert!(source.contains("call<T = unknown, E = RpcJsonObject>("));
        assert!(source.contains("): RpcCallBuilder<T, E>"));

        let fetch_calls = source.matches("this.fetchImpl(").count();
        assert_eq!(
            fetch_calls, 1,
            "generated TypeScript must have exactly one fetch invocation"
        );

        let make_call = source
            .find("async makeCall(): Promise<RpcOutcome<T, E>>")
            .expect("makeCall");
        let fetch = source.find("this.fetchImpl(").expect("fetch invocation");
        let make_call_end = source[make_call..]
            .find("async makeCallOrThrow()")
            .map(|offset| make_call + offset)
            .expect("makeCallOrThrow");

        assert!(
            make_call < fetch,
            "fetch must occur after entering makeCall"
        );
        assert!(
            fetch < make_call_end,
            "fetch must be physically inside makeCall"
        );
        assert!(
            !source[..make_call].contains("this.fetchImpl("),
            "constructing/preparing/chaining a call must not perform network I/O"
        );
    }

    fn typescript_projection_avoids_parameter_properties() {
        let bundle = rpc_client_bundle(&sample_map(), "crate::dto", "public")
            .unwrap_or_else(|error| panic!("bundle generation failed: {error}"));
        assert!(bundle
            .typescript
            .contains("private readonly baseUrl: string;"));
        assert!(bundle
            .typescript
            .contains("public readonly ctx: RpcContext<E>;"));
        assert!(!bundle.typescript.contains("constructor(public readonly"));
        assert!(!bundle
            .typescript
            .contains("constructor(\n    private readonly"));
        assert!(!bundle
            .typescript
            .contains("private readonly baseUrl: string,"));
        assert!(!bundle
            .typescript
            .contains("private readonly fetchImpl: typeof fetch ="));
    }
}
