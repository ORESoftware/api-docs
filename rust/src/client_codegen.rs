//! Shared client-SDK projection from one normalized API route map.
//!
//! Product build tools such as `ores-stack` own repository discovery, audience
//! filtering, and filesystem materialization. This module owns the generated
//! client source so Rust, TypeScript, Dart, and browser WASM cannot drift into
//! four independent RPC dialects.

use std::collections::BTreeMap;

use serde::Serialize;
use serde_json::Value;

use crate::{contract_sha256, rpc_pool_bindings, RouteMap};

const GENERATOR: &str = "ores-api-docs rpc_client_bundle";
const RPC_HTTP_PATH: &str = "/v1/rpc";

#[derive(Clone, Debug, Serialize)]
pub struct RpcClientBundleManifest {
    pub schema_version: u32,
    pub generated_by: &'static str,
    pub service: String,
    pub audience: String,
    pub contract_sha256: String,
    pub operations: Vec<String>,
    pub languages: [&'static str; 4],
    pub http_endpoint: &'static str,
}

#[derive(Clone, Debug)]
pub struct RpcClientBundle {
    pub manifest: RpcClientBundleManifest,
    pub rust: String,
    pub typescript: String,
    pub dart: String,
    pub wasm_cargo_toml: String,
    pub wasm_rust: String,
}

/// Generate all client-language surfaces for an already audience-filtered map.
///
/// The route map remains authoritative. `audience` is carried into generated
/// metadata so internal and public packages cannot be mistaken for each other.
/// Rust body/response bindings may reference authored DTOs under `dto_module`;
/// route-local transport DTOs are generated inline by `rpc_pool_bindings`.
pub fn rpc_client_bundle(
    map: &RouteMap,
    dto_module: &str,
    audience: &str,
) -> Result<RpcClientBundle, String> {
    if audience.trim().is_empty() {
        return Err("client audience must not be empty".to_owned());
    }
    let digest = contract_sha256(map);
    let operations = map.map.keys().cloned().collect::<Vec<_>>();
    let manifest = RpcClientBundleManifest {
        schema_version: 1,
        generated_by: GENERATOR,
        service: map.service.clone(),
        audience: audience.to_owned(),
        contract_sha256: digest.clone(),
        operations,
        languages: ["rust", "typescript", "dart", "wasm"],
        http_endpoint: RPC_HTTP_PATH,
    };
    Ok(RpcClientBundle {
        rust: rust_client(map, dto_module, audience, &digest)?,
        typescript: typescript_client(map, audience, &digest),
        dart: dart_client(map, audience, &digest),
        wasm_cargo_toml: wasm_cargo_toml(map),
        wasm_rust: wasm_client(map, audience, &digest),
        manifest,
    })
}

fn rust_client(
    map: &RouteMap,
    dto_module: &str,
    audience: &str,
    digest: &str,
) -> Result<String, String> {
    let bindings = rpc_pool_bindings(map, dto_module)?;
    Ok(format!(
        "// @generated by {GENERATOR}; do not edit.\n\
         pub const RPC_CONTRACT_SHA256: &str = {digest:?};\n\
         pub const RPC_CLIENT_AUDIENCE: &str = {audience:?};\n\
         pub const RPC_SERVICE: &str = {service:?};\n\
         pub const RPC_HTTP_PATH: &str = {rpc_path:?};\n\n\
         {bindings}",
        service = map.service,
        rpc_path = RPC_HTTP_PATH,
    ))
}

fn typescript_client(map: &RouteMap, audience: &str, digest: &str) -> String {
    let metadata = operation_metadata(map);
    let routes = serde_json::to_string(&metadata).unwrap_or_else(|_| "{}".to_owned());
    format!(
        r#"/** @generated by {generator}; do not edit. */
export const RPC_CONTRACT_SHA256 = {digest:?} as const;
export const RPC_CLIENT_AUDIENCE = {audience:?} as const;
export const RPC_SERVICE = {service:?} as const;
export const RPC_HTTP_PATH = {rpc_path:?} as const;
export const RPC_OPERATIONS = {routes} as const;
export type RpcOperation = keyof typeof RPC_OPERATIONS;
export type RpcJsonObject = Record<string, unknown>;

export interface RpcCallArgs {{
  path?: RpcJsonObject;
  query?: RpcJsonObject;
  headers?: RpcJsonObject;
  body?: unknown;
  traceId?: string;
  spanId?: string;
}}

export interface RpcReceipt {{
  v: 1;
  op: "receipt";
  id: string;
  key: string;
  transport?: "http" | "tcp" | "websocket" | "nats";
  ok: boolean;
  status?: number;
  headers?: RpcJsonObject;
  trailers?: RpcJsonObject;
  body?: unknown;
  error?: RpcJsonObject;
  traceId?: string;
  spanId?: string;
}}

export interface RpcContext<E = RpcJsonObject> {{
  ok: boolean;
  status: number;
  id: string;
  key: string;
  transport: "http" | "tcp" | "websocket" | "nats";
  headers: RpcJsonObject;
  trailers: RpcJsonObject;
  errors: E[];
  traceId?: string;
  traceIds: string[];
  spanId?: string;
}}

export type RpcOutcome<T, E = RpcJsonObject> = readonly [T | undefined, RpcContext<E>];

export class RpcRemoteError<E = RpcJsonObject> extends Error {{
  public readonly ctx: RpcContext<E>;

  constructor(ctx: RpcContext<E>) {{
    super(`RPC ${{ctx.key}} failed with status ${{ctx.status}}`);
    this.ctx = ctx;
  }}
}}

export class RpcCallBuilder<T = unknown, E = RpcJsonObject> {{
  private readonly baseUrl: string;
  private readonly fetchImpl: typeof fetch;
  private readonly key: RpcOperation;
  private readonly args: RpcCallArgs;

  constructor(
    baseUrl: string,
    fetchImpl: typeof fetch,
    key: RpcOperation,
    args: RpcCallArgs = {{}},
  ) {{
    this.baseUrl = baseUrl;
    this.fetchImpl = fetchImpl;
    this.key = key;
    this.args = {{
      ...args,
      path: args.path === undefined ? undefined : {{ ...args.path }},
      query: args.query === undefined ? undefined : {{ ...args.query }},
      headers: args.headers === undefined ? undefined : {{ ...args.headers }},
      body:
        args.body !== null && typeof args.body === "object" && !Array.isArray(args.body)
          ? {{ ...(args.body as RpcJsonObject) }}
          : args.body,
    }};
  }}

  addHeader(name: string, value: unknown): this {{
    this.args.headers ??= {{}};
    this.args.headers[name] = value;
    return this;
  }}

  addHeaders(values: RpcJsonObject): this {{
    this.args.headers = {{ ...(this.args.headers ?? {{}}), ...values }};
    return this;
  }}

  addPathField(name: string, value: unknown): this {{
    this.args.path ??= {{}};
    this.args.path[name] = value;
    return this;
  }}

  addQueryField(name: string, value: unknown): this {{
    this.args.query ??= {{}};
    this.args.query[name] = value;
    return this;
  }}

  addBodyField(name: string, value: unknown): this {{
    if (this.args.body === undefined) this.args.body = {{}};
    if (this.args.body === null || typeof this.args.body !== "object" || Array.isArray(this.args.body)) {{
      throw new TypeError("addBodyField requires an object RPC body");
    }}
    (this.args.body as RpcJsonObject)[name] = value;
    return this;
  }}

  withBody(body: unknown): this {{
    this.args.body = body;
    return this;
  }}

  withTraceId(traceId: string): this {{
    this.args.traceId = traceId;
    return this;
  }}

  withSpanId(spanId: string): this {{
    this.args.spanId = spanId;
    return this;
  }}

  async makeCall(): Promise<RpcOutcome<T, E>> {{
    const id = globalThis.crypto?.randomUUID?.() ?? `ores-${{Date.now()}}-${{Math.random()}}`;
    const envelope = {{
      v: 1,
      op: "call",
      id,
      key: this.key,
      transport: "http",
      ...(this.args.path === undefined ? {{}} : {{ path: this.args.path }}),
      ...(this.args.query === undefined ? {{}} : {{ query: this.args.query }}),
      ...(this.args.headers === undefined ? {{}} : {{ headers: this.args.headers }}),
      ...(this.args.body === undefined ? {{}} : {{ body: this.args.body }}),
      ...(this.args.traceId === undefined ? {{}} : {{ traceId: this.args.traceId }}),
      ...(this.args.spanId === undefined ? {{}} : {{ spanId: this.args.spanId }}),
    }};
    const response = await this.fetchImpl(new URL(RPC_HTTP_PATH, this.baseUrl), {{
      method: "POST",
      headers: {{ "content-type": "application/json" }},
      body: JSON.stringify(envelope),
    }});
    const receipt = (await response.json()) as RpcReceipt;
    if (receipt.id !== id || receipt.key !== this.key) {{
      throw new Error("RPC receipt correlation mismatch");
    }}
    const errors = (receipt.error === undefined ? [] : [receipt.error]) as E[];
    const traceIds = receipt.traceId === undefined ? [] : [receipt.traceId];
    const ctx: RpcContext<E> = {{
      ok: receipt.ok && response.status < 400,
      status: receipt.status ?? response.status,
      id: receipt.id,
      key: receipt.key,
      transport: receipt.transport ?? "http",
      headers: receipt.headers ?? {{}},
      trailers: receipt.trailers ?? {{}},
      errors,
      traceId: receipt.traceId,
      traceIds,
      spanId: receipt.spanId,
    }};
    return [receipt.body as T | undefined, ctx] as const;
  }}

  async makeCallOrThrow(): Promise<T> {{
    const [value, ctx] = await this.makeCall();
    if (!ctx.ok) throw new RpcRemoteError(ctx);
    if (value === undefined) throw new Error(`RPC ${{ctx.key}} succeeded without a body`);
    return value;
  }}
}}

export class RpcClient {{
  private readonly baseUrl: string;
  private readonly fetchImpl: typeof fetch;

  constructor(
    baseUrl: string,
    fetchImpl: typeof fetch = globalThis.fetch.bind(globalThis),
  ) {{
    this.baseUrl = baseUrl;
    this.fetchImpl = fetchImpl;
  }}

  prepare<T = unknown, E = RpcJsonObject>(
    key: RpcOperation,
    args: RpcCallArgs = {{}},
  ): RpcCallBuilder<T, E> {{
    if (!(key in RPC_OPERATIONS)) {{
      throw new Error(`RPC operation not generated for this audience: ${{String(key)}}`);
    }}
    return new RpcCallBuilder<T, E>(this.baseUrl, this.fetchImpl, key, args);
  }}

  call<T = unknown, E = RpcJsonObject>(
    key: RpcOperation,
    args: RpcCallArgs = {{}},
  ): RpcCallBuilder<T, E> {{
    return this.prepare<T, E>(key, args);
  }}
}}
"#,
        generator = GENERATOR,
        digest = digest,
        audience = audience,
        service = map.service,
        rpc_path = RPC_HTTP_PATH,
        routes = routes,
    )
}

