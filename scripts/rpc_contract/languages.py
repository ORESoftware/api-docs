"""Digest-bound v1 Rust, TypeScript, Dart, Gleam, and Go surfaces."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .model import ContractError, _ROUTE_GEN


def _go_ident(key: str) -> str:
    value = _ROUTE_GEN.pascal(key)
    if not value or not value[0].isalpha():
        raise ContractError(f"cannot form Go identifier from {key!r}")
    return value


def gen_go(contract: dict[str, Any]) -> str:
    digest = contract["contractSha256"]
    mechanisms_json = json.dumps(
        _mechanism_manifest(contract), separators=(",", ":"), sort_keys=True
    )
    identifiers: dict[str, str] = {}
    for operation in contract["operations"]:
        identifier = _go_ident(operation["key"])
        previous = identifiers.get(identifier)
        if previous is not None:
            raise ContractError(
                f"Go identifier collision: {previous!r} and "
                f"{operation['key']!r} both become {identifier}"
            )
        identifiers[identifier] = operation["key"]
    lines = [
        "// Code generated by rpc-contract-bundle.py; DO NOT EDIT.",
        "package rpccontract",
        "",
        f'const Service = {json.dumps(contract["service"])}',
        f'const ContractSHA256 = {json.dumps(digest)}',
        "",
        (
            "// RPCMechanismsJSON is the exact machine-readable transport, "
            "framing, delivery, alias, and queue contract."
        ),
        f"const RPCMechanismsJSON = {json.dumps(mechanisms_json)}",
        "",
        "type RouteKey string",
        "",
        "const (",
    ]
    route_names = [f"Route{_go_ident(op['key'])}" for op in contract["operations"]]
    const_width = max(map(len, route_names), default=0)
    for op, route_name in zip(contract["operations"], route_names, strict=True):
        lines.append(
            f'\t{route_name:<{const_width}} RouteKey = {json.dumps(op["key"])}'
        )
    struct_fields = [
        ("Key", "RouteKey"),
        ("Path", "string"),
        ("Methods", "[]string"),
        ("Transports", "[]string"),
        ("TCPFraming", "string"),
        ("Delivery", "string"),
        ("AliasOf", "string"),
        ("OptoSyncTable", "string"),
        ("OptoSyncOperation", "string"),
    ]
    field_width = max(map(lambda item: len(item[0]), struct_fields))
    lines.extend([")", "", "type Route struct {"])
    lines.extend(
        f"\t{name:<{field_width}} {field_type}" for name, field_type in struct_fields
    )
    lines.extend(["}", "", "var Routes = map[RouteKey]Route{"])
    for op in contract["operations"]:
        methods = ", ".join(json.dumps(item) for item in op["methods"])
        transports = ", ".join(json.dumps(item) for item in op["transports"])
        route_name = f"Route{_go_ident(op['key'])}"
        values = [
            ("Key", route_name),
            ("Path", json.dumps(op["path"])),
            ("Methods", f"[]string{{{methods}}}"),
            ("Transports", f"[]string{{{transports}}}"),
            ("TCPFraming", json.dumps(op.get("tcpFraming") or "")),
            ("Delivery", json.dumps(op["delivery"])),
            ("AliasOf", json.dumps(op.get("aliasOf") or "")),
            ("OptoSyncTable", json.dumps((op.get("optoSync") or {}).get("table", ""))),
            (
                "OptoSyncOperation",
                json.dumps((op.get("optoSync") or {}).get("operation", "")),
            ),
        ]
        lines.append(f"\t{route_name}: {{")
        lines.extend(
            f"\t\t{name + ':':<{field_width + 1}} {value}," for name, value in values
        )
        lines.append("\t},")
    lines.extend(["}", ""])
    return "\n".join(lines)


def _write(path: Path, content: str | dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, dict):
        text = json.dumps(content, indent=2, sort_keys=True) + "\n"
    else:
        text = content.rstrip("\n") + "\n"
    path.write_text(text, encoding="utf-8")


def _mechanism_manifest(contract: dict[str, Any]) -> dict[str, Any]:
    fields = (
        "key",
        "path",
        "methods",
        "transports",
        "tcpFraming",
        "delivery",
        "aliasOf",
        "optoSync",
    )
    return {
        operation["key"]: {
            field: operation[field]
            for field in fields
            if field in operation
        }
        for operation in contract["operations"]
    }


def _insert_before(text: str, marker: str, declaration: str, language: str) -> str:
    if marker not in text:
        raise ContractError(f"{language} renderer no longer contains {marker!r}")
    return text.replace(marker, declaration + marker, 1)


def gen_typescript_bound(contract: dict[str, Any], mapping: dict[str, Any]) -> str:
    base = _ROUTE_GEN.gen_typescript(contract["service"], mapping)
    manifest = json.dumps(_mechanism_manifest(contract), indent=2, sort_keys=True)
    declaration = (
        f'export const RPC_CONTRACT_SHA256 = "{contract["contractSha256"]}" as const;\n'
        f"export const RPC_MECHANISMS = {manifest} as const;\n\n"
    )
    return _insert_before(base, "export const SERVICE", declaration, "TypeScript")


def gen_rust_bound(contract: dict[str, Any], mapping: dict[str, Any]) -> str:
    base = _ROUTE_GEN.gen_rust(contract["service"], mapping)
    manifest = json.dumps(_mechanism_manifest(contract), separators=(",", ":"), sort_keys=True)
    declaration = (
        "/// Digest of the normalized RPC contract and docs bundle.\n"
        f'pub const RPC_CONTRACT_SHA256: &str = "{contract["contractSha256"]}";\n'
        "/// Transport, framing, delivery, alias, and queue metadata for every route.\n"
        f'pub const RPC_MECHANISMS_JSON: &str = r###"{manifest}"###;\n\n'
    )
    return _insert_before(base, "pub const SERVICE", declaration, "Rust")


def gen_dart_bound(contract: dict[str, Any], mapping: dict[str, Any]) -> str:
    base = _ROUTE_GEN.gen_dart(contract["service"], mapping)
    manifest = json.dumps(_mechanism_manifest(contract), separators=(",", ":"), sort_keys=True)
    declaration = (
        "/// Digest of the normalized RPC contract and docs bundle.\n"
        f"const String rpcContractSha256 = '{contract['contractSha256']}';\n"
        "/// Full route mechanism metadata, bound by [rpcContractSha256].\n"
        f"const String rpcMechanismsJson = r'''{manifest}''';\n\n"
    )
    return _insert_before(base, "const String kService", declaration, "Dart")


def gen_gleam_bound(contract: dict[str, Any], mapping: dict[str, Any]) -> str:
    base = _ROUTE_GEN.gen_gleam(contract["service"], mapping)
    manifest = json.dumps(
        json.dumps(_mechanism_manifest(contract), separators=(",", ":"), sort_keys=True)
    )
    declaration = (
        "/// Digest of the normalized RPC contract and docs bundle.\n"
        f'pub const rpc_contract_sha256: String = "{contract["contractSha256"]}"\n'
        "/// Full route mechanism metadata, bound by rpc_contract_sha256.\n"
        f"pub const rpc_mechanisms_json: String = {manifest}\n\n"
    )
    return _insert_before(base, "pub const service", declaration, "Gleam")
