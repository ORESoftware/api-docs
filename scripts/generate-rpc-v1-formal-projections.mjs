#!/usr/bin/env node

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const CHECK = process.argv.includes('--check');

const readText = (relative) => readFile(path.join(ROOT, relative), 'utf8');
const readJson = async (relative) => JSON.parse(await readText(relative));

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

function projectionDigest({ projection, tsp, schemas, protobufLock }) {
  const payload = {
    formatVersion: 1,
    projection,
    typespec: tsp,
    jsonSchemas: schemas,
    protobufLock,
  };
  return createHash('sha256').update(canonicalJson(payload), 'utf8').digest('hex');
}

function stripComment(line) {
  return line.split('//', 1)[0].trim();
}

function bracedBody(text, kind, name) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((line) => new RegExp(`^\\s*${kind}\\s+${name}\\s*\\{`).test(stripComment(line)));
  assert.notEqual(start, -1, `TypeSpec ${kind} missing: ${name}`);
  let depth = (lines[start].match(/\{/g) ?? []).length - (lines[start].match(/\}/g) ?? []).length;
  const body = [];
  for (const line of lines.slice(start + 1)) {
    depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
    if (depth <= 0) break;
    body.push(line);
  }
  assert.equal(depth, 0, `unclosed TypeSpec ${kind}: ${name}`);
  return body;
}

function modelFields(tsp, name) {
  const fields = new Map();
  for (const raw of bracedBody(tsp, 'model', name)) {
    const line = stripComment(raw);
    const match = /^(`[^`]+`|[A-Za-z_][A-Za-z0-9_]*)(\?)?\s*:\s*(.+);$/.exec(line);
    if (!match) continue;
    fields.set(match[1].replaceAll('`', ''), { required: match[2] !== '?' });
  }
  return fields;
}

function enumValues(tsp, name) {
  return bracedBody(tsp, 'enum', name)
    .map(stripComment)
    .filter(Boolean)
    .map((line) => line.replace(/,$/, '').split(':', 1)[0].trim());
}

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replaceAll('_', '-').toLowerCase();
}

function snake(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replaceAll('-', '_').toLowerCase();
}

const WIT_TYPES = new Map([
  ['uint32', 'u32'],
  ['string', 'string'],
  ['Transport', 'transport'],
  ['bytes', 'list<u8>'],
  ['bool', 'bool'],
]);

const DAFNY_TYPES = new Map([
  ['uint32', 'int'],
  ['string', 'string'],
  ['Transport', 'Transport'],
  ['bytes', 'seq<int>'],
  ['bool', 'bool'],
]);

function fieldInventory(projection, tsp, model) {
  const fields = modelFields(tsp, model);
  const protoTypes = projection.messages?.[model]?.protoTypes;
  assert.ok(protoTypes && typeof protoTypes === 'object', `${model} protoTypes missing`);
  assert.deepEqual([...fields.keys()].sort(), Object.keys(protoTypes).sort(), `${model} TypeSpec/projection field inventory drift`);
  return Object.entries(protoTypes).map(([name, protoType]) => ({
    name,
    required: fields.get(name).required,
    protoType,
  }));
}

function renderWit({ projection, tsp, digest }) {
  const transports = enumValues(tsp, 'Transport');
  assert.deepEqual(transports, ['http', 'tcp', 'websocket', 'nats'], 'Transport enum drift');
  const lines = [
    '// GENERATED by scripts/generate-rpc-v1-formal-projections.mjs; DO NOT EDIT.',
    `// projection_sha256: ${digest}`,
    '// Derived component-boundary evidence only; TypeSpec and authored JSON Schema remain peer authorities.',
    '// JSON containers are canonical UTF-8 JSON bytes and must pass the shared semantic validator after decoding.',
    '',
    'package ores:rpc@1.0.0;',
    '',
    'interface types {',
    '  enum transport {',
    ...transports.map((value) => `    ${kebab(value)},`),
    '  }',
    '',
  ];

  for (const model of ['RpcCall', 'RpcReceipt']) {
    lines.push(`  record ${kebab(model)} {`);
    for (const field of fieldInventory(projection, tsp, model)) {
      const base = WIT_TYPES.get(field.protoType);
      assert.ok(base, `unsupported WIT projection type: ${field.protoType}`);
      const witType = field.required ? base : `option<${base}>`;
      lines.push(`    ${kebab(field.name)}: ${witType},`);
    }
    lines.push('  }', '');
  }

  const service = projection.service;
  assert.equal(service?.name, 'RpcService', 'WIT world expects RpcService');
  assert.equal(service?.methods?.length, 1, 'WIT world expects exactly one RPC method');
  const method = service.methods[0];
  assert.equal(method.name, 'Call', 'WIT world expects Call');
  assert.equal(method.requestPayload, 'RpcCall');
  assert.equal(method.responsePayload, 'RpcReceipt');
  assert.equal(method.clientStreaming, false);
  assert.equal(method.serverStreaming, false);

  lines.push(
    '}',
    '',
    'world rpc-service {',
    '  use types.{rpc-call, rpc-receipt};',
    '  export call: func(call: rpc-call) -> rpc-receipt;',
    '}',
    '',
  );
  return lines.join('\n');
}

function dafnyType(field) {
  const base = DAFNY_TYPES.get(field.protoType);
  assert.ok(base, `unsupported Dafny projection type: ${field.protoType}`);
  return field.required ? base : `Opt<${base}>`;
}

function renderDafny({ projection, tsp, digest }) {
  const transports = enumValues(tsp, 'Transport');
  assert.deepEqual(transports, ['http', 'tcp', 'websocket', 'nats'], 'Transport enum drift');
  const callFields = fieldInventory(projection, tsp, 'RpcCall');
  const receiptFields = fieldInventory(projection, tsp, 'RpcReceipt');
  const receiptNames = new Set(receiptFields.map(({ name }) => name));
  for (const required of ['ok', 'status', 'body', 'error']) {
    assert.ok(receiptNames.has(required), `Dafny receipt-state proof requires ${required}`);
  }

  const ctor = (model, fields) => [
    `  datatype ${model} = Mk${model}(`,
    ...fields.map((field, index) => `    ${snake(field.name)}: ${dafnyType(field)}${index + 1 === fields.length ? '' : ','}`),
    '  )',
    '',
  ];

  return [
    '// GENERATED by scripts/generate-rpc-v1-formal-projections.mjs; DO NOT EDIT.',
    `// projection_sha256: ${digest}`,
    '// Derived proof evidence only; it is not a contract authority or runtime validator.',
    '// seq<int> models canonical JSON/wire bytes abstractly; byte-range and JSON parsing remain runtime concerns.',
    '',
    'module OresRpcV1 {',
    '  datatype Transport = Http | Tcp | Websocket | Nats',
    '  datatype Opt<T> = Absent | Present(value: T)',
    '',
    ...ctor('RpcCall', callFields),
    ...ctor('RpcReceipt', receiptFields),
    '  predicate UInt32(value: int) {',
    '    0 <= value < 4294967296',
    '  }',
    '',
    '  predicate SuccessStatus(status: Opt<int>) {',
    '    status.Absent? || (status.Present? && 200 <= status.value < 400)',
    '  }',
    '',
    '  predicate ErrorStatus(status: Opt<int>) {',
    '    status.Absent? || (status.Present? && 400 <= status.value < 600)',
    '  }',
    '',
    '  predicate SuccessState(receipt: RpcReceipt) {',
    '    receipt.ok && receipt.error.Absent? && SuccessStatus(receipt.status)',
    '  }',
    '',
    '  predicate ErrorState(receipt: RpcReceipt) {',
    '    !receipt.ok && receipt.error.Present? && receipt.body.Absent? && ErrorStatus(receipt.status)',
    '  }',
    '',
    '  predicate ValidReceiptState(receipt: RpcReceipt) {',
    '    SuccessState(receipt) || ErrorState(receipt)',
    '  }',
    '',
    '  lemma SuccessAndErrorAreDisjoint(receipt: RpcReceipt)',
    '    ensures !(SuccessState(receipt) && ErrorState(receipt))',
    '  {}',
    '',
    '  lemma ValidReceiptHasExactlyOneState(receipt: RpcReceipt)',
    '    requires ValidReceiptState(receipt)',
    '    ensures SuccessState(receipt) != ErrorState(receipt)',
    '  {}',
    '',
    '  lemma PresentSuccessStatusIsBounded(status: Opt<int>)',
    '    requires SuccessStatus(status) && status.Present?',
    '    ensures 200 <= status.value < 400',
    '  {}',
    '',
    '  lemma PresentErrorStatusIsBounded(status: Opt<int>)',
    '    requires ErrorStatus(status) && status.Present?',
    '    ensures 400 <= status.value < 600',
    '  {}',
    '}',
    '',
  ].join('\n');
}

async function writeOrCheck(relative, content) {
  const target = path.join(ROOT, relative);
  if (CHECK) {
    assert.equal(await readFile(target, 'utf8'), content, `generated output drift: ${relative}`);
    return;
  }
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content, 'utf8');
  await chmod(target, 0o444);
}

const projection = await readJson('idl/rpc-v1.projection.json');
const tsp = await readText('idl/typespec/v1.tsp');
const schemas = {
  'json-schema/rpc-call.schema.json': await readJson('json-schema/rpc-call.schema.json'),
  'json-schema/rpc-receipt.schema.json': await readJson('json-schema/rpc-receipt.schema.json'),
};
const protobufLock = await readJson('idl/protobuf.lock.json');
const digest = projectionDigest({ projection, tsp, schemas, protobufLock });
const proto = await readText('idl/protobuf/ores/rpc/v1/rpc.proto');
assert.match(proto, new RegExp(`^// GENERATED by scripts/generate-rpc-v1-projections\\.py; DO NOT EDIT\\.\\n// projection_sha256: ${digest}$`, 'm'), 'Protobuf projection digest is stale');

await writeOrCheck('generated/rpc-v1/wit/ores-rpc-v1.wit', renderWit({ projection, tsp, digest }));
await writeOrCheck('generated/rpc-v1/dafny/ores_rpc_v1.dfy', renderDafny({ projection, tsp, digest }));
console.log(`${CHECK ? 'verified' : 'generated'} RPC v1 WIT/Dafny evidence ${digest}`);
